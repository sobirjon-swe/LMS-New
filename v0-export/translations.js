const translationMap = new Map(
  uiTranslations.map(([uz, ru, en]) => [uz, [uz, null, ru, en]]),
);
const sourceText = new WeakMap();
function toCyrillic(text) {
  const multi = {
    "O‘": "Ў",
    "o‘": "ў",
    "G‘": "Ғ",
    "g‘": "ғ",
    Oʻ: "Ў",
    oʻ: "ў",
    Gʻ: "Ғ",
    gʻ: "ғ",
    Sh: "Ш",
    sh: "ш",
    Ch: "Ч",
    ch: "ч",
    Yo: "Ё",
    yo: "ё",
    Yu: "Ю",
    yu: "ю",
    Ya: "Я",
    ya: "я",
    Ye: "Е",
    ye: "е",
  };
  const singles = {
    a: "а",
    b: "б",
    d: "д",
    e: "е",
    f: "ф",
    g: "г",
    h: "ҳ",
    i: "и",
    j: "ж",
    k: "к",
    l: "л",
    m: "м",
    n: "н",
    o: "о",
    p: "п",
    q: "қ",
    r: "р",
    s: "с",
    t: "т",
    u: "у",
    v: "в",
    x: "х",
    y: "й",
    z: "з",
  };
  return text
    .replace(
      /O[‘ʻ]|o[‘ʻ]|G[‘ʻ]|g[‘ʻ]|Sh|sh|Ch|ch|Yo|yo|Yu|yu|Ya|ya|Ye|ye/g,
      (m) => multi[m],
    )
    .replace(/[A-Za-z]/g, (c) => {
      const mapped = singles[c.toLowerCase()];
      return mapped
        ? c === c.toUpperCase()
          ? mapped.toUpperCase()
          : mapped
        : c;
    });
}
function translatePhrase(source) {
  const language = demo.language || 0;
  if (!language) return source;
  const trimmed = source.trim();
  if (!trimmed || /^[\d\W]+$/u.test(trimmed)) return source;
  if (language === 1) return toCyrillic(source);
  const exact = translationMap.get(trimmed)?.[language];
  if (exact) return source.replace(trimmed, exact);
  if (trimmed.startsWith("Dashboard / "))
    return (
      "Dashboard / " +
      (translationMap.get(trimmed.slice(12))?.[language] || trimmed.slice(12))
    );
  return source;
}
function translateUI(root = document.body) {
  document.documentElement.lang = ["uz-Latn", "uz-Cyrl", "ru", "en"][
    demo.language || 0
  ];
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  nodes.forEach((node) => {
    if (
      node.parentElement?.closest(
        "script,style,.glyph,#language,#languages,textarea,input",
      )
    )
      return;
    if (!sourceText.has(node)) sourceText.set(node, node.textContent);
    node.textContent = translatePhrase(sourceText.get(node));
  });
  root.querySelectorAll("[placeholder]").forEach((el) => {
    el.dataset.originalPlaceholder ||= el.placeholder;
    el.placeholder = translatePhrase(el.dataset.originalPlaceholder);
  });
}
